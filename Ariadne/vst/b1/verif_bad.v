(* Negative tests for B1a.  Each mutant driver (bad_uaf.c, bad_nonull.c,
   generated by make_b1.py) is still called b1 and is checked against the
   same b1_spec and the same sglib funspecs as in verif_b1.v.  The proof
   replays verif_b1.v's steps up to the line marked BAD, where the next
   Floyd step must fail: `Fail tac` succeeds only if `tac` fails, so this
   file compiles exactly when VST refuses every bad step.

   This is a regression check on the tactics, not the guarantee: the
   guarantee is VST's soundness.  If semax_body held for a mutant, the
   mutant would be safe in Clight, but each has a stuck execution (a load
   from a freed block; a store through NULL when malloc fails). *)
Require Import VST.floyd.proofauto.
Require Import VST.floyd.library.
Require Import B1.b1.
Require Import B1.verif_b1.
Require B1.bad_uaf B1.bad_nonull.

(* (a) Use after free: the forward walk runs after the free loop. *)
Lemma body_b1_uaf: semax_body Vprog Gprog B1.bad_uaf.f_b1 b1_spec.
Proof.
  start_function.
  forward. forward.
  (* Loop 1, as in verif_b1.v. *)
  forward_loop
    (EX k: Z, EX s: list (val * int),
     PROP (0 <= k <= n)
     LOCAL (temp _k (Vint (Int.repr k)); temp _last (Vint (Int.repr 0));
            lvar _the_list (tptr t_dll) v_the_list; lvar _it t_it v_it;
            temp _input input; temp _n (Vint (Int.repr n)); gvars gv)
     SEP (mem_mgr gv; data_at sh (tarray tint n) (map Vint contents) input;
          data_at Tsh (tptr t_dll) (hd_ptr s) v_the_list; dll nullval s;
          data_at_ Tsh t_it v_it))
  continue:
    (EX k: Z, EX s: list (val * int),
     PROP (0 <= k < n)
     LOCAL (temp _k (Vint (Int.repr k)); temp _last (Vint (Int.repr 0));
            lvar _the_list (tptr t_dll) v_the_list; lvar _it t_it v_it;
            temp _input input; temp _n (Vint (Int.repr n)); gvars gv)
     SEP (mem_mgr gv; data_at sh (tarray tint n) (map Vint contents) input;
          data_at Tsh (tptr t_dll) (hd_ptr s) v_the_list; dll nullval s;
          data_at_ Tsh t_it v_it))
  break:
    (EX s: list (val * int),
     PROP ()
     LOCAL (temp _last (Vint (Int.repr 0));
            lvar _the_list (tptr t_dll) v_the_list; lvar _it t_it v_it;
            temp _input input; temp _n (Vint (Int.repr n)); gvars gv)
     SEP (mem_mgr gv; data_at sh (tarray tint n) (map Vint contents) input;
          data_at Tsh (tptr t_dll) (hd_ptr s) v_the_list; dll nullval s;
          data_at_ Tsh t_it v_it)).
  - forward. Exists 0 (@nil (val * int)).
    unfold dll, hd_ptr, hd_or, dlseg. entailer!.
  - Intros k s.
    forward_if.
    2: { forward. Exists s. entailer!. }
    forward_call (t_dll, gv).
    Intros l.
    if_tac.
    + forward_if.
      * forward. Exists s. entailer!.
      * congruence.
    + Intros.
      forward_if.
      { congruence. }
      forward. forward.
      forward_call (Tsh, v_the_list, l, Znth k contents, Vundef, Vundef, s).
      Exists k ((l, Znth k contents) :: s). entailer!.
  - Intros k s. forward. Exists (k + 1) s. entailer!.
  - (* Loop 3 (free every element), as in verif_b1.v. *)
    Intros s.
    (* kept for the walk below: the head is a pointer or NULL *)
    assert_PROP (is_pointer_or_null (hd_ptr s)) by entailer!.
    forward.
    forward_call (Tsh, v_it, s). forward.
    forward_loop
      (EX t: list (val * int), EX q: val,
       PROP ()
       LOCAL (temp _l (hd_ptr t); temp _last (Vint (Int.repr 0));
              lvar _the_list (tptr t_dll) v_the_list; lvar _it t_it v_it;
              temp _input input; temp _n (Vint (Int.repr n)); gvars gv)
       SEP (mem_mgr gv;
            data_at sh (tarray tint n) (map Vint contents) input;
            data_at Tsh (tptr t_dll) (hd_ptr s) v_the_list;
            iter_at (hd_ptr t) (hd_ptr (tl t)) v_it;
            dll q t))
    continue:
      (EX t: list (val * int), EX p: val,
       PROP ()
       LOCAL (temp _l p; temp _last (Vint (Int.repr 0));
              lvar _the_list (tptr t_dll) v_the_list; lvar _it t_it v_it;
              temp _input input; temp _n (Vint (Int.repr n)); gvars gv)
       SEP (mem_mgr gv;
            data_at sh (tarray tint n) (map Vint contents) input;
            data_at Tsh (tptr t_dll) (hd_ptr s) v_the_list;
            iter_at p (hd_ptr t) v_it;
            dll p t))
    break:
      (PROP ()
       LOCAL (temp _last (Vint (Int.repr 0));
              lvar _the_list (tptr t_dll) v_the_list; lvar _it t_it v_it;
              temp _input input; temp _n (Vint (Int.repr n)); gvars gv)
       SEP (mem_mgr gv;
            data_at sh (tarray tint n) (map Vint contents) input;
            data_at Tsh (tptr t_dll) (hd_ptr s) v_the_list;
            data_at_ Tsh t_it v_it)).
    + Exists s nullval. unfold iter_at, it_val. entailer!.
    + Intros t q. unfold iter_at, it_val.
      destruct t as [| [p y] t].
      * forward_if.
        { discriminate. }
        forward. unfold dll. simpl dlseg. entailer!.
      * unfold dll. rewrite dlseg_cons. Intros.
        forward_if.
        2: { assert_PROP (isptr p) by entailer!. subst p. contradiction. }
        forward_call (t_dll, p, gv).
        { rewrite if_false by (intro; subst; contradiction). cancel. }
        Exists t p. unfold dll, iter_at, it_val. entailer!.
    + Intros t p. unfold iter_at, it_val.
      forward_call (Tsh, v_it, p, nullval, hd_ptr t, nullval, p, t).
      { left; auto. }
      forward. Exists t p. unfold iter_at, it_val. entailer!.
    + (* The walk after the free loop.  Every node was given to free, so
         nothing in SEP mentions the head p that the_list still holds.
         The empty list is harmless; look at a non-empty one. *)
      destruct s as [| [p y] s']; [shelve |].
      simpl hd_ptr.
      forward_loop
        (PROP ()
         LOCAL (temp _l p; temp _last (Vint (Int.repr 0));
                lvar _the_list (tptr t_dll) v_the_list; lvar _it t_it v_it;
                temp _input input; temp _n (Vint (Int.repr n)); gvars gv)
         SEP (mem_mgr gv;
              data_at sh (tarray tint n) (map Vint contents) input;
              data_at Tsh (tptr t_dll) p v_the_list;
              data_at_ Tsh t_it v_it))
      break:
        (PROP ()
         LOCAL (temp _last (Vint (Int.repr 0));
                lvar _the_list (tptr t_dll) v_the_list; lvar _it t_it v_it;
                temp _input input; temp _n (Vint (Int.repr n)); gvars gv)
         SEP (mem_mgr gv;
              data_at sh (tarray tint n) (map Vint contents) input;
              data_at_ Tsh (tptr t_dll) v_the_list;
              data_at_ Tsh t_it v_it)).
      * forward. all: entailer!.      (* l = the_list; *)
      * (* BAD: if (!(l != NULL)) break; -- comparing the freed p with
           NULL is defined only if p is a valid pointer, and nothing in
           SEP says so: the side condition `... |-- denote_tc_test_eq p
           nullval` is left and cannot be proved. *)
        forward_if.
        Fail solve [entailer!; auto with valid_pointer].
        shelve.
        (* BAD: last = l->i; -- even granting the comparison, the load
           needs a data_at for p, and free consumed it. *)
        Fail forward.
Abort.

(* (b) No NULL check after malloc: l->i = input[k] may store through
   NULL. *)
Lemma body_b1_nonull: semax_body Vprog Gprog B1.bad_nonull.f_b1 b1_spec.
Proof.
  start_function.
  forward. forward.
  forward_loop
    (EX k: Z, EX s: list (val * int),
     PROP (0 <= k <= n)
     LOCAL (temp _k (Vint (Int.repr k)); temp _last (Vint (Int.repr 0));
            lvar _the_list (tptr t_dll) v_the_list; lvar _it t_it v_it;
            temp _input input; temp _n (Vint (Int.repr n)); gvars gv)
     SEP (mem_mgr gv; data_at sh (tarray tint n) (map Vint contents) input;
          data_at Tsh (tptr t_dll) (hd_ptr s) v_the_list; dll nullval s;
          data_at_ Tsh t_it v_it))
  break:
    (EX s: list (val * int),
     PROP ()
     LOCAL (temp _last (Vint (Int.repr 0));
            lvar _the_list (tptr t_dll) v_the_list; lvar _it t_it v_it;
            temp _input input; temp _n (Vint (Int.repr n)); gvars gv)
     SEP (mem_mgr gv; data_at sh (tarray tint n) (map Vint contents) input;
          data_at Tsh (tptr t_dll) (hd_ptr s) v_the_list; dll nullval s;
          data_at_ Tsh t_it v_it)).
  - forward. Exists 0 (@nil (val * int)).
    unfold dll, hd_ptr, hd_or, dlseg. entailer!.
  - Intros k s.
    forward_if.
    2: { forward. Exists s. entailer!. }
    forward_call (t_dll, gv).           (* l = malloc(sizeof(dllist)); *)
    Intros l.
    forward.                            (* t = input[k]; *)
    (* BAD: l->i = t; -- malloc's postcondition gives the cell only
       under `if eq_dec l nullval then emp else ...`, so there is no
       data_at for l; in the l == NULL case there is none at all. *)
    Fail forward.
    if_tac.
    + Fail forward.
Abort.
