/* Stage-1 client 2 of the approved client survey (plan M6).
   Several lists (A7): build two lists from alternate input values,
   iterate the first and add copies of its payloads to the second,
   free both by iteration.
   Generated by make_clients.py from ../dllist.c (the six sglib
   functions, verbatim); do not edit. */

#include <stddef.h>
#include <stdlib.h>

typedef struct dllist {
  int i;
  struct dllist *ptr_to_next;
  struct dllist *ptr_to_previous;
} dllist;
struct sglib_dllist_iterator {
  dllist *currentelem;
  dllist *prevelem;
  dllist *nextelem;
  int (*subcomparator)(dllist *, dllist *);
  dllist *equalto;
};

dllist *sglib_dllist_it_next(struct sglib_dllist_iterator *it);
void sglib_dllist_add(dllist **list, dllist *elem) {
  {
    {
      if ((*list) == NULL) {
        {
          (*list) = (elem);
          (*list)->ptr_to_next = (*list)->ptr_to_previous = NULL;
        };
      } else {
        (elem)->ptr_to_next = (*list);
        (elem)->ptr_to_previous = (*list)->ptr_to_previous;
        (*list)->ptr_to_previous = (elem);
        if ((elem)->ptr_to_previous != NULL)
          (elem)->ptr_to_previous->ptr_to_next = (elem);
      }
    }
    (*list) = (elem);
  };
}
dllist *sglib_dllist_get_first(dllist *list) {
  dllist *result;
  {
    dllist *_dll_;
    _dll_ = (list);
    if (_dll_ != NULL) {
      for (; _dll_->ptr_to_previous != NULL; _dll_ = _dll_->ptr_to_previous)
        ;
    }
    (result) = _dll_;
  };
  return (result);
}
dllist *sglib_dllist_get_last(dllist *list) {
  dllist *result;
  {
    dllist *_dll_;
    _dll_ = (list);
    if (_dll_ != NULL) {
      for (; _dll_->ptr_to_next != NULL; _dll_ = _dll_->ptr_to_next)
        ;
    }
    (result) = _dll_;
  };
  return (result);
}
dllist *sglib_dllist_it_init_on_equal(struct sglib_dllist_iterator *it,
                                      dllist *list,
                                      int (*subcomparator)(dllist *, dllist *),
                                      dllist *equalto) {
  it->subcomparator = subcomparator;
  it->equalto = equalto;
  it->prevelem = list;
  it->nextelem = list;
  if (list != NULL)
    it->nextelem = list->ptr_to_next;
  return (sglib_dllist_it_next(it));
}
dllist *sglib_dllist_it_init(struct sglib_dllist_iterator *it, dllist *list) {
  return (sglib_dllist_it_init_on_equal(it, list, NULL, NULL));
}
dllist *sglib_dllist_it_next(struct sglib_dllist_iterator *it) {
  dllist *ce, *eq;
  int (*scp)(dllist *, dllist *);
  ce = it->prevelem;
  it->prevelem = NULL;
  if (it->subcomparator != NULL) {
    eq = it->equalto;
    scp = it->subcomparator;
    while (ce != NULL) {
      if (scp(eq, ce) == 0)
        break;
      ce = ce->ptr_to_previous;
    }
  }
  if (ce != NULL) {
    it->prevelem = ce->ptr_to_previous;
  } else {
    ce = it->nextelem;
    it->nextelem = NULL;
    if (it->subcomparator != NULL) {
      eq = it->equalto;
      scp = it->subcomparator;
      while (ce != NULL) {
        if (scp(ce, eq) == 0)
          break;
        ce = ce->ptr_to_next;
      }
    }
    if (ce != NULL)
      it->nextelem = ce->ptr_to_next;
  }
  it->currentelem = ce;
  return (ce);
};

/* free every node of the list that has node p, by one iteration */
static void free_all(dllist *p) {
  struct sglib_dllist_iterator it;
  dllist *l;
  for (l = sglib_dllist_it_init(&it, p); l != NULL;
       l = sglib_dllist_it_next(&it))
    free(l);
}

int input[5] = {6, 7, 3, 4, 7};

void client(const int *input, int n) {
  dllist *a = NULL, *b = NULL, *l, *c;
  struct sglib_dllist_iterator it;
  for (int k = 0; k < n; k++) {
    l = malloc(sizeof(dllist));
    if (l == NULL)
      break;
    l->i = input[k];
    if (k % 2 == 0)
      sglib_dllist_add(&a, l);
    else
      sglib_dllist_add(&b, l);
  }
  for (l = sglib_dllist_it_init(&it, a); l != NULL;
       l = sglib_dllist_it_next(&it)) {
    c = malloc(sizeof(dllist));
    if (c == NULL)
      break;
    c->i = l->i;
    sglib_dllist_add(&b, c);
  }
  free_all(a);
  free_all(b);
}

int main(void) {
  client(input, 5);
  return 0;
}
