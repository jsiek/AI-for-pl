Theorem wp_goal :
  forall (t:Numbers.BinNums.Z -> Numbers.BinNums.Z) (t1:addr -> addr)
    (a:addr) (a1:addr) (i:Numbers.BinNums.Z) (i1:Numbers.BinNums.Z)
    (i2:Numbers.BinNums.Z) (l:Init.Datatypes.list addr)
    (l1:Init.Datatypes.list addr),
  let x := list.Length.length l1 in
  let x1 := list.Length.length l in
  ((nth l1 i2) = (nth l i)) -> (0%Z <= i2)%Z -> (0%Z <= i1)%Z ->
  (0%Z <= i)%Z -> (i2 < x)%Z -> (i1 < x1)%Z -> (i < x1)%Z ->
  P_dll t t1 null a1 l1 -> P_dll t t1 null a l ->
  ((nth l1 i1) = (nth l i1)) /\ (i1 < x)%Z.
Proof.
intros t t1 a a1 i i1 i2 l l1 x x1 h1 h2 h3 h4 h5 h6 h7 h8 h9.
(* Backward: a shared node has the same index in both whole lists, and
   the two lists agree up to it. *)
assert (Back : forall (d : nat) (p q : Z), p = Z.of_nat d -> (0 <= q)%Z ->
          (p < x1)%Z -> (q < x)%Z -> nth l1 q = nth l p ->
          p = q /\ (forall k, (0 <= k)%Z -> (k <= p)%Z -> nth l1 k = nth l k)).
{ induction d as [| d IH]; intros p q Hp Hq Hpx Hqx Heq.
  - simpl in Hp. subst p.
    destruct (Q_dll_links t t1 null a l 0%Z) as [_ [Hl0 _]]; [lia | exact Hpx | exact h9 |].
    specialize (Hl0 eq_refl).
    assert (Hq0 : q = 0%Z).
    { apply (Q_dll_first t t1 a1 l1 q); [ rewrite Heq; exact Hl0 | lia | exact Hqx | exact h8 ]. }
    subst q. split; [reflexivity |].
    intros k Hk0 Hk. assert (k = 0%Z) by lia. subst k. exact Heq.
  - rewrite Nat2Z.inj_succ in Hp.
    destruct (Z.eq_dec q 0) as [Hq0 | Hq0].
    + exfalso. subst q.
      destruct (Q_dll_links t t1 null a1 l1 0%Z) as [_ [Hl0 _]]; [lia | exact Hqx | exact h8 |].
      specialize (Hl0 eq_refl). rewrite Heq in Hl0.
      assert (p = 0%Z) by (apply (Q_dll_first t t1 a l p); [exact Hl0 | lia | exact Hpx | exact h9]).
      lia.
    + destruct (Q_dll_links t t1 null a l p) as [_ [_ Hlp]]; [lia | exact Hpx | exact h9 |].
      destruct (Q_dll_links t t1 null a1 l1 q) as [_ [_ Hlq]]; [lia | exact Hqx | exact h8 |].
      specialize (Hlp ltac:(lia)). specialize (Hlq Hq0).
      rewrite Heq in Hlq. rewrite Hlq in Hlp.
      destruct (IH ((-1) + p)%Z ((-1) + q)%Z) as [E Hk]; [lia | lia | lia | lia | exact Hlp |].
      split; [lia |].
      intros k Hk0 Hkp. destruct (Z.eq_dec k p) as [Ek | Ek].
      * subst k. assert (q = p) by lia. subst q. exact Heq.
      * apply Hk; lia. }
destruct (Back (Z.to_nat i) i i2) as [Eii Hpre]; [lia | lia | lia | lia | exact h1 |].
(* Forward: from the shared node on, the lists agree and end together. *)
assert (Fwd : forall (d : nat) (k : Z), k = (i + Z.of_nat d)%Z -> (k < x1)%Z ->
          (k < x)%Z /\ nth l1 k = nth l k).
{ induction d as [| d IH]; intros k Hk Hkx.
  - simpl in Hk. assert (k = i) by lia. subst k.
    split; [lia | apply Hpre; lia].
  - rewrite Nat2Z.inj_succ in Hk.
    destruct (IH ((-1) + k)%Z) as [Hkx' Heq']; [lia | lia |].
    destruct (Q_dll_links t t1 null a l ((-1) + k)%Z) as [[_ [Hn _]] _]; [lia | lia | exact h9 |].
    destruct (Q_dll_links t t1 null a l k) as [[Hnn _] _]; [lia | exact Hkx | exact h9 |].
    destruct (Q_dll_links t t1 null a1 l1 ((-1) + k)%Z) as [[_ [Hn1 Hn1']] _]; [lia | exact Hkx' | exact h8 |].
    rewrite Heq' in Hn1, Hn1'.
    specialize (Hn ltac:(lia)).
    replace (1 + ((-1) + k))%Z with k in Hn by lia.
    destruct (Z_le_dec (2 + ((-1) + k)) x) as [Hle | Hle].
    + specialize (Hn1 Hle). replace (1 + ((-1) + k))%Z with k in Hn1 by lia.
      split; [lia | rewrite <- Hn1; exact Hn].
    + exfalso. specialize (Hn1' Hle). rewrite Hn1' in Hn. apply Hnn. symmetry. exact Hn. }
destruct (Z_le_dec i1 i) as [Hle | Hlt].
- split; [apply Hpre; lia | lia].
- destruct (Fwd (Z.to_nat (i1 - i)) i1) as [Hx Heq]; [lia | exact h6 |].
  split; [exact Heq | exact Hx].
Qed.

