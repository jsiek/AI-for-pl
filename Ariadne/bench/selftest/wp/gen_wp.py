"""Build st_wp.c: B1's annotated sglib functions at the self-test's
instantiation, for WP (plan Q12; the subcomparator path with myListCmp).

   usage (from this directory): python3 -I gen_wp.py

1. st_gen.c: sglib's SGLIB_DEFINE_DL_LIST_{PROTOTYPES,FUNCTIONS}
   (DoubleLinkedList, myListCmp, previous, next), expanded as ../b1/gen.sh
   does (cpp with B1's verification refactor #1 applied to a copy of
   sglib.h, then clang-format), after selftest.c's own struct MyIntList,
   typedef and myListCmp, copied from ../../sglib/selftest.c by pattern.
2. The annotated sglib part of ../../b1/b1.c, renamed (dllist ->
   DoubleLinkedList, ptr_to_previous -> previous, ptr_to_next -> next,
   dllist_cmp_reads -> st_cmp_reads, comparator set (0) -> (1, myListCmp),
   B1's comparator expression -> myListCmp(a, b)).
3. The check: the renamed code, annotations stripped, equals st_gen.c's
   token for token (else exit 1), so the annotations sit on sglib's own
   expansion and the renaming is checked by a tool, not assumed.
4. st_wp.c = st_gen.c's types and myListCmp, the spec, myListCmp's
   contract, the renamed annotated functions, and driver.c (ours)."""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ARIADNE = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(ARIADNE, "harness"))
from acsl_expand import annotations  # noqa: E402

st = open(os.path.join(ARIADNE, "bench", "sglib", "selftest.c")).read()
struct = re.search(r"struct MyIntList \{.*?\n\};\n", st, re.S).group(0)
typedef = re.search(r"typedef struct MyIntList DoubleLinkedList;\n",
                    st).group(0)
cmp = re.search(r"int myListCmp\(.*?\n\}\n", st, re.S).group(0)
open(os.path.join(HERE, "st_gen_in.c"), "w").write(
    "/* Input of gen_wp.py (generated; do not edit). */\n"
    '#include "sglib.h"\n\n' + struct + "\n" + typedef + "\n" + cmp +
    "\nSGLIB_DEFINE_DL_LIST_PROTOTYPES(DoubleLinkedList, myListCmp, "
    "previous, next);\nSGLIB_DEFINE_DL_LIST_FUNCTIONS(DoubleLinkedList, "
    "myListCmp, previous, next);\n")
r = subprocess.run(
    [os.path.join(ARIADNE, "env", "run.sh"), "sh", "-c", """
  set -e
  mkdir -p /tmp/sglib_r
  python3 -I /ariadne/bench/b1/refactor/it_next_calls.py \
    /ariadne/bench/sglib/sglib.h /tmp/sglib_r/sglib.h
  cpp -P -nostdinc -I /ariadne/bench/b1/stub -I /tmp/sglib_r st_gen_in.c \
    > /tmp/st.i
  clang-format-14 --style="{BasedOnStyle: LLVM, ColumnLimit: 79}" /tmp/st.i
"""], cwd=HERE, capture_output=True, text=True)
if r.returncode:
    sys.exit("gen_wp.py: expansion failed:\n" + r.stderr)
gen = r.stdout
open(os.path.join(HERE, "st_gen.c"), "w").write(gen)
k = gen.index("\nextern ") + 1
gen_types, gen_funs = gen[:k], gen[k:]

b1 = open(os.path.join(ARIADNE, "bench", "b1", "b1.c")).read()
B = "/* BEGIN GENERATED (b1_gen.c), part 2: prototypes and functions */\n"
part = b1[b1.index(B) + len(B):b1.index("/* END GENERATED, part 2 */")]
part = part.replace("dllist_cmp_reads", "st_cmp_reads")
part = part.replace("dllist", "DoubleLinkedList")
part = part.replace("ptr_to_previous", "previous")
part = part.replace("ptr_to_next", "next")
part = part.replace("(0))", "(1, myListCmp))")
X = r"(\w+|\(\w+\))"
part, n = re.subn(r"\(\(" + X + r"->i\s*>\s*" + X + r"->i\)\s*-\s*\(\1->i"
                  r"\s*<\s*\2->i\)\)", r"myListCmp(\1, \2)", part)


def tokens(code):
    out, last = [], 0
    for _, s, e, _ in annotations(code):
        out.append(code[last:s])
        last = e
    out.append(code[last:])
    return re.findall(r"\w+|->|==|!=|<=|>=|&&|\|\||\+\+|--|\S",
                      "".join(out))


if tokens(part) != tokens(gen_funs):
    a, b = tokens(part), tokens(gen_funs)
    i = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y),
             min(len(a), len(b)))
    sys.exit(f"gen_wp.py: renamed b1.c code differs from st_gen.c at token "
             f"{i}: {a[i - 5:i + 5]} vs {b[i - 5:i + 5]}")
driver = open(os.path.join(HERE, "driver.c")).read()
open(os.path.join(HERE, "st_wp.c"), "w").write(
    "/* Generated by gen_wp.py; do not edit.  B1's annotated sglib\n"
    "   functions at the self-test's instantiation (see gen_wp.py). */\n"
    "#include <stddef.h>\n#include \"ariadne_alloc.h\"\n"
    "#include \"sglib_dl_list_spec.h\"\n\n"
    "/* BEGIN GENERATED (st_gen.c), part 1 */\n" + gen_types +
    "/* END GENERATED, part 1 */\n\n"
    "/*@ // The fields myListCmp reads (template parameter cmp_reads).\n"
    "    predicate st_cmp_reads{L}(DoubleLinkedList *p) = "
    "\\initialized(&p->n);\n"
    "    SGLIB_DL_LIST_SPEC(DoubleLinkedList, previous, next, st_cmp_reads)\n"
    "    SGLIB_DL_LIST_LEMMAS(DoubleLinkedList, previous, next)\n*/\n\n"
    "/*@ SGLIB_DL_LIST_CONTRACT_COMPARATOR(DoubleLinkedList, st_cmp_reads,\n"
    "                                      e1, e2) */\n"
    "int myListCmp(struct MyIntList *e1, struct MyIntList *e2);\n\n"
    "/* BEGIN GENERATED (st_gen.c), part 2, annotated */\n" + part +
    "/* END GENERATED, part 2 */\n\n" + driver)
print(f"gen_wp.py: wrote st_wp.c ({n} comparator expressions renamed; "
      "code equal to st_gen.c token for token)")
