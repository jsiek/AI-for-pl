(* Negative tests for B1a + B1b.  The mutants are generated by make_b1.py.
   Each driver mutant (bad_uaf.c, bad_uaf_back.c, bad_nonull.c) is still
   called b1 and is checked against the same b1_spec and sglib funspecs as
   in verif_b1.v; each function mutant (bad_nullfirst.c, bad_nulllast.c)
   is checked against the funspec of the function it mutates.  The proof
   replays verif_b1.v's steps up to the line marked BAD, where the next
   Floyd step must fail: `Fail tac` succeeds only if `tac` fails, so this
   file compiles exactly when VST refuses every bad step.

   This is a regression check on the tactics, not the guarantee: the
   guarantee is VST's soundness.  If semax_body held for a driver mutant,
   the mutant would be safe in Clight, but each has a stuck execution (a
   load from a freed block; a store through NULL when malloc fails).  The
   function mutants are safe but return NULL where the funspec promises a
   node of the list. *)
Require Import VST.floyd.proofauto.
Require Import VST.floyd.library.
Require Import B1.b1.
