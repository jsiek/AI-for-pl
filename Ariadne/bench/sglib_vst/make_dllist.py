"""Write dllist.c: sglib's DL list instantiated at B1's `dllist` (macros
expanded by ../b1/gen.sh into ../b1/b1_gen.c, after bug fix #1 and
verification refactor #1), with the six stage-1 functions copied
verbatim (asserted) and nothing else: no driver, no main.  The funspecs
in spec_dllist.v are type-checked against its clightgen output.

    python3 -I make_dllist.py          (from this directory)
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = open(os.path.join(HERE, "..", "b1", "b1_gen.c")).read()
LINES = GEN.split("\n")
FUNCTIONS = ["sglib_dllist_add", "sglib_dllist_get_first",
             "sglib_dllist_get_last", "sglib_dllist_it_init_on_equal",
             "sglib_dllist_it_init", "sglib_dllist_it_next"]


def function(name):
    """The definition of `name` in b1_gen.c (not a prototype), through
    the next line that is `}` or `};` (as ../b1a/make_b1a.py)."""
    for i, line in enumerate(LINES):
        if (not line.startswith("extern") and not line.startswith(" ")
                and re.search(r"\b" + re.escape(name) + r"\(", line)
                and not line.rstrip().endswith(";")):
            start = i
            if LINES[i - 1] and not LINES[i - 1].rstrip().endswith(
                    (";", "}")):
                start = i - 1
            header = "\n".join(LINES[start:]).split("{", 1)[0]
            if LINES[start].startswith("extern") or ";" in header:
                continue
            for j in range(i, len(LINES)):
                if LINES[j] in ("}", "};"):
                    text = "\n".join(LINES[start:j + 1]) + "\n"
                    assert text.count("{") == text.count("}"), name
                    return text
    raise AssertionError(name)


TYPES = GEN[GEN.index("typedef struct dllist {"):GEN.index(
    "};\n", GEN.index("struct sglib_dllist_iterator {")) + 3]
BODIES = [function(f) for f in FUNCTIONS]
for p in [TYPES] + BODIES:
    assert p in GEN, "not verbatim"
PROTO = "dllist *sglib_dllist_it_next(struct sglib_dllist_iterator *it);\n"
open(os.path.join(HERE, "dllist.c"), "w").write(
    "/* sglib's doubly linked list at B1's dllist: the stage-1 functions of\n"
    "   plan M6, verbatim from ../b1/b1_gen.c.  Generated by make_dllist.py;\n"
    "   do not edit. */\n\n#include <stddef.h>\n\n" + TYPES + "\n" + PROTO
    + "".join(BODIES))
