        (EX a: list (val * int), EX b: list (val * int),
         PROP (s1 ++ (p, y) :: s2 = a ++ b; b <> nil)
         LOCAL (temp __dll_ (hd_ptr b))
         SEP (dlseg nullval a (hd_ptr b);
              dlseg (last_or nullval a) b nullval))
