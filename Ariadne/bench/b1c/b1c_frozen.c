/*@ SGLIB_DL_LIST_CONTRACT_IT_NEXT(dllist, ptr_to_previous, ptr_to_next,
                                    (0)) */
dllist *sglib_dllist_it_next(struct sglib_dllist_iterator *it) {
  dllist *ce, *eq;
  int (*scp)(dllist *, dllist *);
  ce = it->prevelem;
  it->prevelem = NULL;
  if (it->subcomparator != NULL) {
    eq = it->equalto;
    scp = it->subcomparator;
    while (ce != NULL) {
      if (scp(eq, ce) == 0)
        break;
      ce = ce->ptr_to_previous;
    }
  }
  if (ce != NULL) {
    it->prevelem = ce->ptr_to_previous;
  } else {
    ce = it->nextelem;
    it->nextelem = NULL;
    if (it->subcomparator != NULL) {
      eq = it->equalto;
      scp = it->subcomparator;
      while (ce != NULL) {
        if (scp(ce, eq) == 0)
          break;
        ce = ce->ptr_to_next;
      }
    }
    if (ce != NULL)
      it->nextelem = ce->ptr_to_next;
  }
  it->currentelem = ce;
  return (ce);
};

/* Driver (B1c), modelled on sglib's self-test of the DL list: build a
   list from input[0..n-1] with sglib_dllist_add; walk it once with the
   iterator without freeing, summing the payloads (unsigned, so the sum
   cannot overflow) and recording the node at position m / 2; if the walk
   returned a node, add a new node before that recorded node (add with
   *list set to a middle node); then iterate again starting from the new
   node, which exercises the iterator's backward phase, freeing every node
   returned.  Returns the sum. */
/*@ requires 0 <= n && \valid_read(input + (0 .. n - 1));
    requires \initialized(input + (0 .. n - 1));
    requires !heap(\base_addr(input));
    // every live node's payload is initialised (the walks read it, and
    // the list predicates cover only the links)
    requires payload_init: \forall dllist *q; live(q) ==> \initialized(&q->i);
*/
unsigned b1(const int *input, int n) {
  dllist *l = NULL, *the_list = NULL, *mid = NULL, *e = NULL;
  struct sglib_dllist_iterator it;
  unsigned sum = 0, c = 0;
  int m = 0;
  for (int k = 0; k < n; k++) {
  before_alloc:
    l = ariadne_alloc_dllist();
    if (l == NULL)
      break;
    l->i = input[k];
    sglib_dllist_add(&the_list, l);
    m++;
  }
  for (l = sglib_dllist_it_init(&it, the_list); l != NULL;
       l = sglib_dllist_it_next(&it)) {
    sum += (unsigned)l->i;
    if (c == (unsigned)m / 2)
      mid = l;
    c++;
  }
  if (mid != NULL) {
  before_alloc2:
    e = ariadne_alloc_dllist();
    if (e != NULL) {
      e->i = 0;
      the_list = mid;
      sglib_dllist_add(&the_list, e);
    }
  }
  for (l = sglib_dllist_it_init(&it, the_list); l != NULL;
       l = sglib_dllist_it_next(&it)) {
  before_free:
    ariadne_free_dllist(l);
  }
  return sum;
}
