#!/usr/bin/env python3
"""
REALLMS Coq prover (plan section 12.2, tier 1): give a REALLMS model a WP
goal file (session/interactive/*.v, generated by Why3's Coq driver) and
tools to explore and check, until `coqc` accepts its proof script.

The model writes only the script between the goal's `Proof.` and `Qed.`;
the statement and the Why3 context are never touched.  A script passes
iff coqc accepts the file and the script contains no admit, Admitted,
Abort, Axiom, ... (so it cannot end the proof early or add assumptions).

Tools exposed to the model:
  read_file(path, start?, end?)   read a slice of a file under Ariadne/
  grep(pattern, path?)            search files under Ariadne/
  coq_query(command)              run Search / Check / Print / About /
                                  Locate in the goal file's context
  show_goals(script)              the goal state after a partial script
                                  (--backend coqc)
  run_tactics(tactics, state?)    run tactics from a saved proof state and
                                  return the new state's goals
                                  (--backend petanque)
  check_proof(script)             the whole proof; ok + coqc's errors

Backends: `coqc` reruns the whole goal file for every call; `petanque`
keeps one Pétanque session (petanque.py) and runs tactics step by step
from saved states.  Either way the final verdict is coqc's.

Only a compact JSON report goes to stdout; the transcript goes to --log.
coqc runs in the M0 image (Ariadne/env/run.sh).  Key handling is in
scripts/reallms_client.py; the key is never printed or logged.
"""
import argparse
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ARIADNE = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(os.path.dirname(ARIADNE), "scripts"))
sys.path.insert(0, HERE)  # petanque.py (python3 -I drops the script dir)
from reallms_client import read_key, tool_loop  # noqa: E402
from petanque import Petanque, PetanqueError, PetanqueTimeout  # noqa: E402

RUN = os.path.join(ARIADNE, "env", "run.sh")
WORK = os.path.join(HERE, ".work")  # under Ariadne/, so /ariadne/... in the image
COQC = ("coqc -native-compiler no "
        "-R /home/rocq/.opam/4.14.2/lib/why3/coq Why3")
FORBIDDEN = re.compile(
    r"\b(admit|Admitted|Abort|give_up|Qed|Defined|Save|Axiom|Axioms|"
    r"Parameter|Parameters|Hypothesis|Hypotheses|Variable|Variables|"
    r"Conjecture|Context|Declare|Extract|Unset|Set|Theorem|Lemma|"
    r"Definition|Fixpoint|Require|Import|Module|End|Section)\b")
QUERIES = ("Search", "SearchPattern", "SearchRewrite", "Check", "Print",
           "About", "Locate")


def normalise(script):
    """Models often wrap the script in Proof. ... Qed.; the harness adds
    those itself, so drop a leading `Proof.` and one final `Qed.` or
    `Defined.` (anything after them would still be refused)."""
    s = script.strip("\n")
    s = re.sub(r"^\s*Proof\.", "", s)
    s = re.sub(r"\s*\b(Qed|Defined)\.\s*$", "", s)
    return s


def sentences(script):
    """Split a script into Coq sentences: each ends at a `.` followed by
    whitespace or the end, outside comments and strings.  Bullets and
    braces stay attached to the sentence after them."""
    out, i, start, depth, n = [], 0, 0, 0, len(script)
    while i < n:
        if script.startswith("(*", i):
            depth, i = depth + 1, i + 2
            continue
        if depth and script.startswith("*)", i):
            depth, i = depth - 1, i + 2
            continue
        c = script[i]
        if not depth and c == '"':
            j = script.find('"', i + 1)
            i = n if j < 0 else j + 1
            continue
        if not depth and c == "." and (i + 1 == n or script[i + 1].isspace()) \
                and not script.startswith("..", i - 1):
            out.append(script[start:i + 1].strip())
            start = i + 1
        i += 1
    if script[start:].strip():
        out.append(script[start:].strip())
    return [x for x in out if x]


def show_goals_json(g, limit=6000):
    """Pétanque goals as Coq prints them: hypotheses and conclusion of
    the first goal, conclusions of the others."""
    goals = g.get("goals") or []
    lines = []
    if not goals:
        # A bullet's branch is done: show the goals waiting under the
        # enclosing bullets (the model needs their hypotheses too).
        goals = [x for lr in g.get("stack") or [] for side in lr
                 for x in side]
        if not goals:
            msg = "No goals left."
            if g.get("shelf"):
                msg += f" {len(g['shelf'])} shelved goal(s): Unshelve."
            return msg
        lines.append("No goals in focus (this bullet's branch is done). "
                     "Unfocused goals, reached with the next bullet:")
    lines.append(f"{len(goals)} goal(s)")
    first = goals[0]
    for h in first.get("hyps") or []:
        body = f" := {h['def']}" if h.get("def") else ""
        lines.append(f"  {', '.join(h['names'])}{body} : {h['ty']}")
    lines.append("  ============================")
    lines.append("  " + first["ty"].replace("\n", "\n  "))
    for k, other in enumerate(goals[1:], 2):
        lines.append(f"goal {k}: " + other["ty"].replace("\n", "\n  "))
    if g.get("bullet"):
        lines.append("(" + g["bullet"] + ")")
    out = "\n".join(lines)
    return out if len(out) <= limit else out[:limit] + "\n... (truncated)"


def split_goal(text):
    """(prefix through `Proof.`, current script, suffix from `Qed.`) of
    the Why3 goal `wp_goal`."""
    m = re.search(r"\(\* Why3 goal \*\)\s*\nTheorem wp_goal\b", text)
    if not m:
        sys.exit("no `(* Why3 goal *) Theorem wp_goal` in the file")
    p = text.index("\nProof.", m.end()) + len("\nProof.")
    q = text.rindex("\nQed.")
    return text[:p], text[p:q], text[q:]


class Worker:
    def __init__(self, path, timeout, fh, blank=False, backend="coqc"):
        self.path = os.path.abspath(path)
        self.blank = blank
        self.backend = backend
        self.pet = None
        self.states = [""]  # state id -> script; 0 = the statement
        self.pet_states = {}  # state id -> Pétanque state, this session
        self.cur = 0
        self.pet_restarts = 0
        self.text = open(self.path).read()
        self.prefix, self.script, self.suffix = split_goal(self.text)
        self.timeout = timeout
        self.fh = fh
        self.last_ok = False
        self.last_script = None
        self.last_errors = ""
        self.counts = {}
        self.coqc_runs = 0
        self.err_loc = None
        self.last_call, self.repeats = None, 0
        os.makedirs(WORK, exist_ok=True)

    def statement(self):
        m = re.search(r"\(\* Why3 goal \*\)\s*\n", self.prefix)
        return self.prefix[m.end():]

    def _coqc(self, body):
        """Run coqc on body in the image; return (ok, output)."""
        self.coqc_runs += 1
        d = tempfile.mkdtemp(dir=WORK)
        name = "goal.v"
        with open(os.path.join(d, name), "w") as f:
            f.write(body)
        inner = os.path.relpath(d, ARIADNE)
        cmd = [RUN, "sh", "-c",
               f"cd /ariadne/{inner} && timeout {self.timeout} {COQC} {name}"]
        try:
            r = subprocess.run(cmd, capture_output=True, text=True,
                               timeout=self.timeout + 60)
            out, rc = (r.stdout + r.stderr), r.returncode
        except subprocess.TimeoutExpired:
            out, rc = "(timeout)", 124
        finally:
            subprocess.run(["rm", "-rf", d])
        if rc == 124:
            out += f"\n(coqc timed out after {self.timeout} s)"
        # Error locations refer to our temp file.  The script starts on
        # the line after the prefix's last line (`Proof.`).
        base = self.prefix.count("\n") + 1
        self.err_loc = None
        m = re.search(r'File "[^"]*", line (\d+), characters (\d+)-', out)
        if m and int(m.group(1)) > base:
            self.err_loc = (int(m.group(1)) - base, int(m.group(2)))
        out = re.sub(r'File "[^"]*", line (\d+)',
                     lambda m: f"script line {int(m.group(1)) - base}"
                     if int(m.group(1)) > base else f"context line {m.group(1)}",
                     out)
        return rc == 0, out.strip()[-4000:]

    def _state_before_error(self, script):
        """The goal state just before the step coqc rejected (after a
        failed run whose error is in the script), or ""."""
        if not self.err_loc:
            return ""
        line, col = self.err_loc
        lines = script.split("\n")
        if line > len(lines):
            return ""
        before = "\n".join(lines[:line - 1] + [lines[line - 1][:col]])
        if re.search(r"(^|\s)([-+*]+|\{)\s*$", before):
            before += " idtac."  # keep the focus a trailing bullet opened
        ok, out = self._coqc(self.prefix + "\n" + before
                             + "\nShow.\nAdmitted.\n")
        return out if ok else ""

    # ---- tools ----
    def _safe(self, path):
        p = os.path.realpath(os.path.join(ARIADNE, path))
        if p != ARIADNE and not p.startswith(ARIADNE + os.sep):
            raise ValueError("path outside Ariadne/")
        return p

    def _hidden(self, p):
        """With --blank, the target and every goal file next to it (the
        other session proofs) have their proofs hidden."""
        return (self.blank and p.endswith(".v")
                and os.path.dirname(p) == os.path.dirname(self.path))

    def _visible(self, p):
        """A file's text as the model may see it."""
        text = open(p, errors="replace").read()
        if self._hidden(p):
            try:
                pre, _, suf = split_goal(text)
                text = pre + "\n(* proof hidden *)" + suf
            except SystemExit:
                pass
        return text

    def read_file(self, path, start=None, end=None):
        p = self._safe(path)
        if "/." in p[len(ARIADNE):]:
            raise ValueError("hidden directory")
        lines = self._visible(p).split("\n")
        s = max(1, int(start or 1))
        e = min(len(lines), int(end or s + 199))
        return "\n".join(f"{i}: {lines[i - 1]}" for i in range(s, e + 1))

    def grep(self, pattern, path=None):
        """grep -E over .v/.c/.h/.md files, through _visible."""
        rx = re.compile(pattern)
        root = self._safe(path or ".")
        files = [root] if os.path.isfile(root) else sorted(
            os.path.join(d, n) for d, ds, ns in os.walk(root)
            for n in ns if n.endswith((".v", ".c", ".h", ".md"))
            and "/." not in d[len(ARIADNE):])
        hits = []
        for p in files:
            for i, l in enumerate(self._visible(p).split("\n"), 1):
                if rx.search(l):
                    hits.append(f"{os.path.relpath(p, ARIADNE)}:{i}:{l[:200]}")
                    if len(hits) >= 40:
                        return "\n".join(hits)
        return "\n".join(hits) or "(no matches)"

    def coq_query(self, command):
        c = command.strip()
        if not c.endswith("."):
            c += "."
        if not c.startswith(QUERIES) or c.count(".") > 1 and \
                re.search(r"\.\s+\S", c):
            return "(only one Search/Check/Print/About/Locate command)"
        if self.backend == "petanque":
            st = self._pet_state(0)
            r, err = self._pet_run(st, c)
            if err:
                return "Error: " + err
            return "\n".join(m for _, m in r.get("feedback") or []) \
                or "(no output)"
        ok, out = self._coqc(self.prefix.rsplit("\n(* Why3 goal *)", 1)[0]
                             + "\n" + c + "\n")
        return out or "(no output)"

    def show_goals(self, script):
        script = normalise(script)
        if FORBIDDEN.search(script):
            return "(script uses a forbidden command)"
        ok, out = self._coqc(self.prefix + "\n" + script
                             + "\nShow.\nAdmitted.\n")
        if not ok:
            state = self._state_before_error(script)
            if state:
                out += "\n\nGoal state just before the failing step:\n" + state
        return out or "(no goals left)"

    def check_proof(self, script):
        script = normalise(script)
        bad = FORBIDDEN.search(script)
        if bad:
            self.last_ok = False
            self.last_errors = f"forbidden in a proof script: {bad.group(1)}"
            return {"ok": False, "errors": self.last_errors}
        ok, out = self._coqc(self.prefix + "\n" + script.strip("\n")
                             + self.suffix)
        self.last_ok, self.last_script, self.last_errors = ok, script, out
        if ok:
            return {"ok": True, "errors": ""}
        return {"ok": False, "errors": out,
                "goal_state_before_failing_step":
                    self._state_before_error(script.strip("\n"))
                    or "(not available)"}

    # ---- Pétanque backend ----
    def _pet_open(self):
        """Start a Pétanque session on a copy of the goal file whose
        proof is `Admitted.` (so pet never sees the existing proof)."""
        d = tempfile.mkdtemp(dir=WORK, prefix="pet_")
        with open(os.path.join(d, "goal.v"), "w") as f:
            f.write(self.prefix + "\nAdmitted.\n")
        self.pet = Petanque(d)
        self.pet_dir = d
        root = self.pet.start("goal.v", "wp_goal", timeout=300)["st"]
        self.pet_states = {0: root}
        if not self.states:
            self.states = [""]

    def _pet_close(self):
        if self.pet:
            self.pet.close()
            subprocess.run(["rm", "-rf", self.pet_dir])
            self.pet = None

    def _pet_state(self, sid):
        """The Pétanque state for our state id, replaying its script
        after a restart."""
        if self.pet is None:
            self._pet_open()
        if sid not in self.pet_states:
            r = self.pet.run(self.pet_states[0], self.states[sid],
                             timeout=self.timeout)
            self.pet_states[sid] = r["st"]
        return self.pet_states[sid]

    def _pet_run(self, st, tac):
        try:
            return self.pet.run(st, tac, timeout=self.timeout), None
        except PetanqueTimeout:
            self._pet_close()  # the session is stuck; replay later
            self.pet_restarts += 1
            return None, f"timed out after {self.timeout} s"
        except PetanqueError as e:
            msg = str(e)
            return None, msg[len("Coq: "):] if msg.startswith("Coq: ") else msg

    def run_tactics(self, tactics, state=None):
        script = normalise(tactics)
        bad = FORBIDDEN.search(script)
        if bad:
            return {"ok": False, "error": f"forbidden: {bad.group(1)}"}
        sid = self.cur if state is None else int(state)
        if not 0 <= sid < len(self.states):
            return {"ok": False, "error": f"no state {sid}; states are "
                    f"0..{len(self.states) - 1} (0 = the statement)"}
        st = self._pet_state(sid)
        done = []
        # Bullets and braces are dropped: from a saved state the model
        # cannot know the bullet level, and without them each tactic acts
        # on the first goal (still a valid script for coqc).
        sents = [x for x in (re.sub(r"^(\s*([-+*]+|[{}]))+\s*", "", y)
                             for y in sentences(script)) if x]
        for sent in sents:
            r, err = self._pet_run(st, sent)
            if err:
                g = self.pet.goals(st) if self.pet else None
                return {"ok": False, "failed_sentence": sent, "error": err,
                        "ran_before_it": " ".join(done) or "(nothing)",
                        "state": sid,
                        "goals_before_failing_sentence":
                            show_goals_json(g) if g else "(session restarted)"}
            st = r["st"]
            done.append(sent)
            if r.get("proof_finished"):
                break
        new = (self.states[sid] + "\n" + " ".join(done)).strip("\n")
        self.states.append(new)
        nid = len(self.states) - 1
        self.pet_states[nid] = st
        self.cur = nid
        res = {"ok": True, "state": nid}
        if r.get("proof_finished"):
            # Pétanque says no goals left: the verdict is still coqc's.
            check = self.check_proof(new)
            res["proof_finished"] = True
            res["coqc"] = "accepted: proof complete" if check["ok"] \
                else check["errors"]
        else:
            res["goals"] = show_goals_json(self.pet.goals(st))
        return res

    def dispatch(self, name, args):
        self.counts[name] = self.counts.get(name, 0) + 1
        call = (name, json.dumps(args, sort_keys=True))
        self.repeats = self.repeats + 1 if call == self.last_call else 0
        self.last_call = call
        if self.repeats:
            return (f"(this is the same {name} call as your previous one; "
                    "the result would be identical.  Change the script, or "
                    "look up a lemma with coq_query first.)")
        try:
            return getattr(self, name)(**args) if name in TOOL_NAMES \
                else f"(unknown tool {name})"
        except Exception as e:
            return f"(tool error: {type(e).__name__}: {e})"


def tool(name, desc, **params):
    req = [k for k, v in params.items() if not v.endswith("?")]
    props = {k: {"type": "integer" if v.rstrip("?") == "int" else "string"}
             for k, v in params.items()}
    return {"type": "function", "function": {
        "name": name, "description": desc,
        "parameters": {"type": "object", "properties": props,
                       "required": req}}}


TOOLS = [
    tool("read_file", "Read lines of a file under Ariadne/ (path relative "
         "to Ariadne/).", path="str", start="int?", end="int?"),
    tool("grep", "grep -E over .v/.c/.h/.md files under Ariadne/.",
         pattern="str", path="str?"),
    tool("coq_query", "Run one Search, Check, Print, About or Locate "
         "command in the goal's context (all its definitions, axioms and "
         "Why3 lemmas).", command="str"),
    tool("show_goals", "Run a partial proof script and show the goal "
         "state after it.", script="str"),
    tool("check_proof", "Check a complete proof script (the text between "
         "Proof. and Qed.) with coqc. Returns ok and coqc's errors.",
         script="str"),
]
RUN_TACTICS = tool(
    "run_tactics", "Run one or more tactics (sentences ending in '.') "
    "from a saved proof state: `state` (default: the state your last "
    "successful run_tactics produced; 0 is the goal's statement). "
    "Returns the new state's number and goals, or the failing sentence, "
    "Coq's error and the goals before it. States are kept, so you can "
    "go back to any earlier one. When no goals are left the script is "
    "checked with coqc and you are done.", tactics="str", state="int?")
TOOLS_PET = [t for t in TOOLS if t["function"]["name"] != "show_goals"] \
    + [RUN_TACTICS]
TOOL_NAMES = {t["function"]["name"] for t in TOOLS_PET + TOOLS}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--file", required=True, help="WP goal file (.v)")
    ap.add_argument("--model", default="glm-5.3-flash")
    ap.add_argument("--hint", default="")
    ap.add_argument("--blank", action="store_true",
                    help="hide the proofs of the target and of the goal "
                         "files next to it (also from read_file and grep)")
    ap.add_argument("--backend", choices=("coqc", "petanque"),
                    default="coqc")
    ap.add_argument("--max-seconds", type=int, default=900,
                    help="working-time budget (wall clock minus "
                         "rate-limit waits); 0 for none")
    ap.add_argument("--max-steps", type=int, default=100,
                    help="turn cap, a backstop behind --max-seconds")
    ap.add_argument("--max-tokens", type=int, default=32768,
                    help="output limit per model reply")
    ap.add_argument("--timeout", type=int, default=120,
                    help="seconds per coqc run")
    ap.add_argument("--temperature", type=float, default=0.2)
    ap.add_argument("--log", default=None)
    ap.add_argument("--apply", action="store_true",
                    help="on success write the proof into the file")
    args = ap.parse_args()

    key = read_key()
    fh = open(args.log, "w") if args.log else None
    w = Worker(args.file, args.timeout, fh, args.blank, args.backend)
    current = "" if args.blank else w.script.strip("\n")
    system = (
        "You are a Coq/Rocq 9 proof engineer. You prove one goal generated "
        "by Frama-C/WP through Why3. The goal file defines the memory "
        "model, the ACSL predicates (as Coq definitions or axioms) and "
        "earlier lemmas; Lia and CoqHammer (hammer, sauto) are loaded.\n"
        + ("Tools: coq_query looks up names (Print P_mem. Check "
           "nth_cons. Search Length.length.); run_tactics runs tactics "
           "from a saved proof state and shows the goals after them, so "
           "build the proof a few steps at a time, going back to an "
           "earlier state when a step fails. Do not use bullets (- + *) "
           "or braces with run_tactics: they are dropped, and each tactic "
           "acts on the first goal of the list it shows. A failing step "
           "comes with the goals just before it: read them before trying "
           "again. When no goals are left you are done.\n"
           if args.backend == "petanque" else
           "Tools: coq_query looks up names (Print P_mem. Check nth_cons. "
           "Search Length.length.); show_goals runs a partial script and "
           "shows the goals; check_proof checks a complete script. When a "
           "step fails you also get the goal state just before it: read it "
           "before trying again, and never resend an unchanged script.\n")
        + "The script is the text between Proof. and Qed.; the harness adds "
        "both, so write neither. admit, Admitted, Abort, Defined and new "
        "axioms or definitions are refused.\n"
        "How Why3 encodes goals: integers are Z (`int`); `nth` and "
        "`Length.length` are opaque functions axiomatised by lemmas in "
        "the goal file. Those lemmas usually have hypotheses and "
        "conjunctions (e.g. `0 <= k <= length w -> (k = 0 -> ...) /\\ "
        "(k <> 0 -> ...)`), so `rewrite L` alone fails: use "
        "`destruct (L args) as [H1 H2]` (proving the hypothesis with lia) "
        "or `pose proof`. lia does not know these functions: rewrite "
        "`Length.length (x :: w)` with the length lemma before lia, and "
        "give lia the fact that lengths are nonnegative (pose proof of "
        "the length_pos lemma). Do not use simpl, cbn, compute or unfold "
        "on goals with Z comparisons: they turn < into a match that lia "
        "cannot read. "
        "Check each lemma's statement with coq_query before using it.\n"
        "Iterate with check_proof until it returns ok=true, then stop.")
    user = (f"Goal file: {os.path.relpath(w.path, ARIADNE)}\n\n"
            f"```coq\n{w.statement()}\n```\n"
            + (f"\nCurrent (failing or partial) script:\n```coq\n{current}\n```\n"
               if current else "")
            + (f"\nHint: {args.hint}\n" if args.hint else "")
            + "\nWrite the proof script and verify it with check_proof.")
    tools = TOOLS_PET if args.backend == "petanque" else TOOLS
    try:
        loop = tool_loop(
            args.model, key, system, user, tools, w.dispatch,
            solved=lambda: w.last_ok, check_tool="check_proof",
            nudge="You did not call a tool. Continue the proof with a "
                  "tool call now (check_proof or run_tactics), then fix "
                  "what Coq reports.",
            max_steps=args.max_steps, temperature=args.temperature, fh=fh,
            max_tokens=args.max_tokens, max_seconds=args.max_seconds)
    finally:
        w._pet_close()
    report = {
        "file": os.path.relpath(w.path, ARIADNE), "model": args.model,
        "status": loop["status"], "solved": w.last_ok,
        "steps": loop["steps"], "seconds": loop["seconds"],
        "waited": loop["waited"], "max_seconds": args.max_seconds,
        "cut_off": loop["cut_off"], "max_tokens": args.max_tokens,
        "usage": loop["usage"], "tool_calls": w.counts,
        "coqc_runs": w.coqc_runs, "backend": args.backend,
        "pet_restarts": w.pet_restarts,
        "script": w.last_script if w.last_ok else None,
        "short_error": "" if w.last_ok else (w.last_errors or "")[-600:],
    }
    if args.apply and w.last_ok:
        with open(w.path, "w") as f:
            f.write(w.prefix + "\n" + w.last_script.strip("\n") + w.suffix)
        report["applied"] = True
    print(json.dumps(report, indent=2))
    if fh:
        fh.write("\n===== REPORT =====\n" + json.dumps(report, indent=2) + "\n")
        fh.close()


